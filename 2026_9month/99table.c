/*
 * 九九乘法表（上三角版）
 *
 * 目标：练习嵌套循环和 printf 的格式化输出
 *
 * 预期输出：
 *   1*1=1
 *   1*2=2   2*2=4
 *   1*3=3   2*3=6   3*3=9
 *   ...
 *   1*9=9   2*9=18  ...  9*9=81
 */

#include <stdio.h>

int main(void) {
    /* 外层循环：控制行数，i 从 1 到 9 */
    for (int i = 1; i <= 9; i++) {

        /* 内层循环：每行打印 i 个算式，j 从 1 到 i */
        for (int j = 1; j <= i; j++) {
            /* %-8d 表示：输出整数，左对齐，占 8 个字符宽度
             * 用固定宽度是为了让每一列对齐，否则会参差不齐
             */
            printf("%d*%d=%-8d", j, i, i * j);
        }

        /* 一行打印完，换行 */
        printf("\n");
    }

    return 0;
}
